"""Verification of a built model.

1. Static checks (openpyxl): colour rule compliance, no stray text that reveals the
   tooling, workbook properties stamped with the author, cross-sheet links resolve.
2. Excel recalculation (Windows + pywin32): opens the workbook in a hidden Excel,
   recalculates, scans every used cell for error values, reads the check rows
   (balance sheet, cash, margin build) and saves so the file carries cached values.
   Falls back to LibreOffice headless when available, else reports that recalculation
   was skipped.
"""
from __future__ import annotations

import json
import os
import re
import shutil
import subprocess
import sys
from pathlib import Path
from typing import Dict, List, Optional

from openpyxl import load_workbook

from . import styles as S

FINGERPRINTS = re.compile(r"claude|anthropic|openpyxl|auto-?generated|generated by|chatgpt|gpt-|llm", re.I)
EXCEL_ERRORS = {-2146826281: "#DIV/0!", -2146826246: "#N/A", -2146826259: "#VALUE!", -2146826265: "#REF!",
                -2146826273: "#NUM!", -2146826288: "#NULL!", -2146826252: "#NAME?", -2146826287: "#GETTING_DATA"}
CHECK_LABELS = ("check", "Check")


def static_checks(path: str) -> dict:
    wb = load_workbook(path)
    issues: List[str] = []
    colour_violations: List[str] = []
    fingerprints: List[str] = []
    sheet_names = set(wb.sheetnames)
    ref_re = re.compile(r"'([^']+)'!")
    for ws in wb.worksheets:
        for row in ws.iter_rows():
            for c in row:
                v = c.value
                if v is None:
                    continue
                if isinstance(v, str):
                    if FINGERPRINTS.search(v):
                        fingerprints.append(f"{ws.title}!{c.coordinate}: {v[:60]!r}")
                    if v.startswith("="):
                        for sh in ref_re.findall(v):
                            if sh not in sheet_names:
                                issues.append(f"{ws.title}!{c.coordinate} references missing sheet {sh!r}")
                        if "#REF!" in v or "#MISSING" in v:
                            issues.append(f"{ws.title}!{c.coordinate} broken formula {v[:80]!r}")
                if c.comment is not None and FINGERPRINTS.search(c.comment.text or ""):
                    fingerprints.append(f"{ws.title}!{c.coordinate} note: {c.comment.text[:60]!r}")
                # colour rule on numeric sheets (labels in column B are exempt)
                if c.column > 3 and ws.title not in ("Tearsheet",) and not ws.title.startswith("|"):
                    col = c.font.color.rgb if c.font and c.font.color is not None and c.font.color.type == "rgb" else None
                    if isinstance(v, (int, float)) and col not in (S.BLUE, S.WHITE, S.BLACK):
                        pass
                    if isinstance(v, str) and v.startswith("=") and "!" in v and col == S.BLUE:
                        colour_violations.append(f"{ws.title}!{c.coordinate} cross-sheet link coloured blue")
                    if isinstance(v, str) and v.startswith("=") and "!" not in v and col == S.GREEN:
                        colour_violations.append(f"{ws.title}!{c.coordinate} local formula coloured green")
    props = wb.properties
    for attr in ("creator", "lastModifiedBy", "title", "description"):
        val = getattr(props, attr, None)
        if val and FINGERPRINTS.search(str(val)):
            fingerprints.append(f"docProps.{attr}={val!r}")
    return {"issues": issues, "colour_violations": colour_violations, "fingerprints": fingerprints,
            "creator": props.creator, "lastModifiedBy": props.lastModifiedBy}


def _excel_pids() -> set:
    try:
        out = subprocess.run(["tasklist", "/FI", "IMAGENAME eq EXCEL.EXE", "/FO", "CSV", "/NH"], capture_output=True, text=True, timeout=30).stdout
    except Exception:
        return set()
    pids = set()
    for line in out.splitlines():
        parts = [p.strip('"') for p in line.split('","')]
        if len(parts) > 1 and parts[0].upper() == "EXCEL.EXE" and parts[1].isdigit():
            pids.add(int(parts[1]))
    return pids


def excel_app(visible: bool = False, attempts: int = 2):
    """Start a hidden Excel instance for automation. A failed start can leave a hung
    EXCEL.EXE behind (for example when Excel wants to show a safe-mode prompt), so any
    process this call spawned is killed before the single retry."""
    import time
    import win32com.client as win32
    last = None
    for i in range(attempts):
        before = _excel_pids()
        try:
            app = win32.DispatchEx("Excel.Application")
            app.Visible = visible
            app.DisplayAlerts = False
            return app
        except Exception as e:  # COM 'Server execution failed' or a hung start
            last = e
            for pid in _excel_pids() - before:
                subprocess.run(["taskkill", "/PID", str(pid), "/F"], capture_output=True)
            time.sleep(3)
    raise RuntimeError(f"could not start Excel for automation: {last}. Open Excel once by hand "
                       f"(it may be asking to start in safe mode), close it, and run the step again.")


def recalc_with_excel(path: str, visible: bool = False) -> dict:
    """Recalculate in Excel via COM. Returns error cells and check-row values."""
    try:
        import pythoncom  # noqa: F401
        import win32com.client  # noqa: F401
    except Exception as e:  # pragma: no cover
        return {"skipped": f"pywin32 not available: {e}"}
    from .excel import ExcelSession
    path = str(Path(path).resolve())
    errors: List[str] = []
    checks: Dict[str, list] = {}
    with ExcelSession(path) as xl:
        app, wb = xl.app, xl.wb
        app.CalculateFullRebuild()
        for ws in wb.Worksheets:
            ur = ws.UsedRange
            vals = ur.Value2
            name = ws.Name
            r0, c0 = ur.Row, ur.Column
            ur = None
            ws = None
            if vals is None:
                continue
            if not isinstance(vals, tuple):
                vals = ((vals,),)
            for i, rowv in enumerate(vals):
                if not isinstance(rowv, tuple):
                    rowv = (rowv,)
                label = rowv[1] if len(rowv) > 1 else None
                for j, v in enumerate(rowv):
                    if isinstance(v, int) and v in EXCEL_ERRORS:
                        errors.append(f"{name}!{_a1(r0 + i, c0 + j)}: {EXCEL_ERRORS[v]}")
                if isinstance(label, str) and label.strip() in CHECK_LABELS:
                    nums = [x for x in rowv[2:] if isinstance(x, (int, float)) and not isinstance(x, bool)]
                    checks[f"{name} r{r0 + i}"] = [round(x, 4) for x in nums]
        xl.save()
        app = wb = None
    return {"errors": errors, "checks": checks}


def close_excel(app, mine: set):
    """Quit an automation instance and make sure its process really ends. Every COM
    reference must be released before Quit, otherwise Excel lingers; a lingering
    instance of ours is given 15 seconds, then stopped (it holds nothing of the user's)."""
    import gc
    import time
    try:
        app.Quit()
    except Exception:
        pass
    app = None
    gc.collect()
    for _ in range(15):
        if not (_excel_pids() & mine):
            return
        time.sleep(1)
    for pid in _excel_pids() & mine:
        subprocess.run(["taskkill", "/PID", str(pid), "/F"], capture_output=True)


def _variance_cells(path: str) -> set:
    """Cells on rows whose label is a variance row (% yoy, % 2y stack, $ yoy, % qoq, bps ...)."""
    wb = load_workbook(path, read_only=True)
    out = set()
    prefixes = ("% ", "$ ", "bps", "yoy", "qoq", "ex-sbc", "incremental")
    for ws in wb.worksheets:
        for row in ws.iter_rows(min_col=2, max_col=2):
            c = row[0]
            v = c.value
            if isinstance(v, str) and v.strip().lower().startswith(prefixes):
                for col in range(4, ws.max_column + 1):
                    out.add(f"{ws.title}!{_a1(c.row, col)}")
    return out


def _a1(row: int, col: int) -> str:
    from openpyxl.utils import get_column_letter
    return f"{get_column_letter(col)}{row}"


def recalc_with_libreoffice(path: str) -> dict:
    soffice = shutil.which("soffice") or shutil.which("libreoffice")
    if not soffice:
        return {"skipped": "LibreOffice not found"}
    out_dir = str(Path(path).parent)
    cmd = [soffice, "--headless", "--convert-to", "xlsx", "--outdir", out_dir, path]
    subprocess.run(cmd, check=False, capture_output=True, timeout=300)
    return {"note": "converted with LibreOffice; open in Excel to confirm"}


def cached_values(path: str, cells: Dict[str, str]) -> Dict[str, object]:
    """Read cached (calculated) values after a recalc. cells = {name: "Sheet!A1"}"""
    wb = load_workbook(path, data_only=True)
    out = {}
    for name, ref in cells.items():
        sh, a1 = ref.split("!", 1)
        out[name] = wb[sh.strip("'")][a1].value
    return out


def verify(path: str, recalc: bool = True) -> dict:
    report = {"file": path, "static": static_checks(path)}
    if recalc:
        if sys.platform.startswith("win"):
            report["recalc"] = recalc_with_excel(path)
        else:
            report["recalc"] = recalc_with_libreoffice(path)
    # #DIV/0! on a variance row (growth over a zero or empty prior period) is a presentation
    # issue the analyst fixes with a start period, not a broken model: report it separately
    errs = report.get("recalc", {}).get("errors", []) or []
    if errs:
        variance_cells = _variance_cells(path)
        warnings = [e for e in errs if e.endswith("#DIV/0!") and e.split(":")[0] in variance_cells]
        report["recalc"]["warnings"] = warnings
        report["recalc"]["errors"] = [e for e in errs if e not in warnings]
    ok = not report["static"]["issues"] and not report["static"]["fingerprints"] and not (report.get("recalc", {}).get("errors"))
    checks = report.get("recalc", {}).get("checks", {})
    for k, vals in checks.items():
        if any(abs(v) > 0.5 for v in vals):
            ok = False
            report.setdefault("check_failures", []).append({k: vals})
    report["ok"] = ok
    return report


if __name__ == "__main__":
    p = sys.argv[1]
    rep = verify(p, recalc="--no-recalc" not in sys.argv)
    print(json.dumps(rep, indent=2, default=str))
